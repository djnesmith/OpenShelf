#!/usr/bin/env python3
"""Compares the Edit window's vim engine with real vim.

Runs random key sequences through `vim --clean` and writes a Swift test that
runs the same sequences through VimEngine and expects vim's text and cursor:

    scripts/vim-compare.py [seed] [cases]      # default seed 1, 1500 cases
    swift test --filter VimCompare

Each sequence is 1 to 4 commands, mostly counted operators (d3j, 2d3w, c2iw,
y2ap, d2%, v3jd, x., ...), from a random place in one of a few texts. Each
command runs on its own, as vim's `normal!` does. `u` is left out: vim's
script mode joins all of a sequence's changes into one undo step. Known
difference: "." does not repeat a visual change here (vim does), so sequences
with a visual change followed by "." fail.

The generated file, Tests/OpenShelfTests/VimCompareGenerated.swift, is not
committed. Needs vim on PATH.
"""
import json, os, random, subprocess, sys, tempfile

seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
count = int(sys.argv[2]) if len(sys.argv) > 2 else 1500
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
output = os.path.join(root, "Tests", "OpenShelfTests", "VimCompareGenerated.swift")
random.seed(seed)

texts = [
    "foo bar.baz qux\n  indented line\n\nlast(one) two", "a\nb\nc\nd", "  x = f(a, b);\n   y\n",
    "one two three four five six", "word\n\n\nword2 w3\n", "(a [b {c} d] e)",
    "ax bx cx dx ex\nfx gx (h (i) j) k\n\nline four\nline five\nline six",
    "say \"a (b) c\" [d] {e}", "f(x, \"y\", (z))\n  g[1] <t>u</t>",
]
pool = [
    "d3j", "d2k", "3dj", "2d2j", "d2w", "d3w", "2d3w", "c2wZ<Esc>", "c3eZ<Esc>", "y2eP", "y3wP", ">2j", "<2j",
    ">3>", "d2aw", "c2iwZ<Esc>", "d2fx", "d2tx", "d2Fa", "y2j", "yy2p", "d2d", "d3d", "2dd", "gU3w", "gu2j",
    "g~2w", "d2e", "d2b", "d2B", "d2W", "d2E", "d2l", "d2h", "d2$", "d2G", "d2gg", "d2}", "d2{", "2x", "3X",
    "d2%", "c2jZ<Esc>", "d2i(", "d2a(", "y2ap", "v3jd", "v2wd", "V2jd", "3J", "2rX", "3~", "2p", "d2n", "x.",
    "d3j.", "d2w3.", "2d2w.", "j", "k", "w", "b", "0", "$", "gg", "G",
]


def vim_result(lines, line, column, commands, work):
    script, out = os.path.join(work, "c.vim"), os.path.join(work, "c.json")
    body = "".join('silent! exe "normal! %s"\n' % c.replace("\\", "\\\\").replace('"', '\\"').replace("<Esc>", "\\<Esc>")
                   for c in commands)
    with open(script, "w") as f:
        f.write(f"""set nocompatible autoindent shiftwidth=4 expandtab undolevels=-1
call setline(1, {json.dumps(lines)})
set undolevels=1000
call cursor({line + 1}, {column + 1})
{body}call writefile([json_encode(getline(1, '$')), line('.'), col('.')], "{out}")
qa!
""")
    subprocess.run(["vim", "--clean", "-es", "-S", script], capture_output=True, stdin=subprocess.DEVNULL, timeout=10)
    got, l, c = open(out).read().split("\n")[:3]
    got = json.loads(got)
    return "\n".join(got), sum(len(x) + 1 for x in got[:int(l) - 1]) + int(c) - 1


cases = []
with tempfile.TemporaryDirectory() as work:
    for _ in range(count):
        text = random.choice(texts)
        lines = text.split("\n")
        line = random.randrange(len(lines))
        column = random.randrange(max(len(lines[line]), 1))
        commands = [random.choice(pool) for _ in range(random.randint(1, 4))]
        cases.append((text, line, column, commands) + vim_result(lines, line, column, commands, work))


def swift(s): return json.dumps(s, ensure_ascii=False)


rows = ",\n".join(f"        VimCompareCase(text: {swift(t)}, line: {l}, column: {c}, commands: {swift(k)}, vimText: {swift(vt)}, vimCursor: {vc})"
                  for t, l, c, k, vt, vc in cases)
with open(output, "w") as f:
    f.write(f"""// Generated by scripts/vim-compare.py {seed} {count}; not committed.
import Testing
@testable import OpenShelf

struct VimCompareCase: Sendable, CustomStringConvertible {{
    var text: String; var line: Int; var column: Int; var commands: [String]; var vimText: String; var vimCursor: Int
    var description: String {{ "\\(commands.joined(separator: " ")) @\\(line):\\(column) on \\(text.debugDescription)" }}
}}

struct VimCompare {{
    static let cases: [VimCompareCase] = [
{rows}
    ]

    @Test(arguments: cases)
    func matchesVim(_ c: VimCompareCase) {{
        var engine = VimEngine(c.text)
        _ = engine.handle(VimEngineTests.keys("gg0"))
        if c.line > 0 {{ _ = engine.handle(VimEngineTests.keys("\\(c.line)j")) }}
        for _ in 0..<c.column {{ _ = engine.handle(.char("l")) }}
        for command in c.commands {{
            _ = engine.handle(VimEngineTests.keys(command))
            _ = engine.handle(.escape)
        }}
        #expect(engine.string == c.vimText)
        #expect(engine.cursor == c.vimCursor)
    }}
}}
""")
print(f"{count} cases written to {os.path.relpath(output, root)}")
