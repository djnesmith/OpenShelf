import AppKit

/// Everything on a pasteboard, item by item and type by type, so it can be
/// put back exactly after OpenShelf borrows the clipboard.
struct PasteboardSnapshot: Equatable {
    var items: [[NSPasteboard.PasteboardType: Data]]
}

/// The selection's formatted version, as the app copied it.
struct RichText: Equatable {
    enum Kind: Equatable {
        case html
        case rtf

        var fileExtension: String { self == .html ? "html" : "rtf" }
    }

    var kind: Kind
    var data: Data
}

/// The clipboard as the text tools use it. `SystemTextPasteboard` wraps the
/// real one; tests use a fake.
@MainActor
protocol TextPasteboard: AnyObject {
    var changeCount: Int { get }
    func snapshot() -> PasteboardSnapshot
    func restore(_ snapshot: PasteboardSnapshot)
    /// Replaces the contents with `text`, marked so clipboard managers skip it.
    func writeTransient(_ text: String)
    /// Replaces the contents with `text`, for the user to keep (⌥ copies).
    func writeText(_ text: String)
    func string() -> String?
    func richText() -> RichText?
}

/// The two shortcuts OpenShelf presses in the frontmost app.
enum TextShortcut {
    case copy
    case paste
}

/// Presses ⌘C or ⌘V in the frontmost app. `CGEventKeySender` posts real
/// events; tests use a fake that records the presses.
@MainActor
protocol TextKeySender {
    func press(_ shortcut: TextShortcut)
}

@MainActor
final class SystemTextPasteboard: TextPasteboard {
    /// Marks from nspasteboard.org: replaced within seconds, and not
    /// something the user copied, so clipboard histories leave it out.
    static let transientTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    private let pasteboard: NSPasteboard

    init(_ pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    var changeCount: Int { pasteboard.changeCount }

    func snapshot() -> PasteboardSnapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            var types: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { types[type] = data }
            }
            return types
        }
        return PasteboardSnapshot(items: items)
    }

    func restore(_ snapshot: PasteboardSnapshot) {
        pasteboard.clearContents()
        let items = snapshot.items.map { types in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
    }

    func writeTransient(_ text: String) {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for type in Self.transientTypes { item.setData(Data(), forType: type) }
        pasteboard.writeObjects([item])
    }

    func writeText(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    func string() -> String? {
        pasteboard.string(forType: .string)
    }

    func richText() -> RichText? {
        if let html = pasteboard.data(forType: .html) { return RichText(kind: .html, data: html) }
        if let rtf = pasteboard.data(forType: .rtf) { return RichText(kind: .rtf, data: rtf) }
        return nil
    }
}

/// Posts ⌘C and ⌘V as key events, which needs Accessibility. The key codes
/// are for the C and V keys of a QWERTY layout.
struct CGEventKeySender: TextKeySender {
    func press(_ shortcut: TextShortcut) {
        let key: CGKeyCode = shortcut == .copy ? 8 : 9  // kVK_ANSI_C, kVK_ANSI_V
        let source = CGEventSource(stateID: .combinedSessionState)
        for isDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: isDown) else { continue }
            event.flags = .maskCommand
            event.post(tap: .cgSessionEventTap)
        }
    }
}
